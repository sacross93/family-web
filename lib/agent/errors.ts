// 공급자 오류 → 가족이 화면에서 볼 한 문장.
//
// **상태코드도 원문도 화면에 넣지 않는다.** 공급자 원문에는 사용자 본인의 ChatGPT 세션
// 사정이 섞여 있고, 숫자는 가족에게 아무 뜻도 없다.
//
// 이 파일이 따로 있는 이유: 문구가 틀리면 **가족이 고칠 수 없는 일을 고치려고 애쓴다.**
// 실제로 그랬다 — 401 에 "로그인이 풀렸어요. 새로고침해 주세요" 를 띄우고 있었는데,
// 여기서 401 은 **우리 사이트 로그인이 아니라 이 아이의 ChatGPT 연결**이 끊긴 것이다
// (우리 세션이 풀리면 `proxy.ts` 가 로그인 화면으로 보내 이 자리까지 오지도 않는다).
// 새로고침은 영원히 안 듣는다. 무엇이 끊겼는지 말해 줘야 다음 걸음을 뗄 수 있다.

import { AGENT_NAME } from "./name";

export const GENERIC_ERROR = "잠깐 문제가 생겼어요. 다시 해볼까요?";

export function humanError(status?: number): string {
  // 사용량 소진. 기다리면 풀리는 것이라 그렇게 말한다.
  if (status === 429) return "오늘 사용량을 다 썼어요. 잠시 뒤에 다시 해볼까요?";
  // 토큰 만료·권한 없음. **가족이 새로고침으로 고칠 수 없다** — 다시 연결해야 한다고 말한다.
  if (status === 401 || status === 403) {
    return `${AGENT_NAME}가 ChatGPT 연결이 풀렸어요. 다시 연결해야 대답할 수 있어요.`;
  }
  return GENERIC_ERROR;
}
